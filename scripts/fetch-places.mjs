#!/usr/bin/env node
// Generates src/lib/places.ts from Atlanta BeltLine Inc's public ArcGIS server.
//
// These are the parks, public art and trail-access points behind
// beltline.org/map. They are geographic facts, not editorial content, and they
// change rarely -- so this writes a static module rather than adding a table
// and a runtime fetch. Re-run when the source updates:
//
//   node scripts/fetch-places.mjs
//
// Note this deliberately imports *location data only*. No BeltLine branding,
// logos or palette -- v1 is independent (see AGENTS.md standing decisions).
import { writeFileSync } from "node:fs";

const BASE = "https://gis.beltline.org/server/rest/services";
const LAYERS = [
  { service: "ABI_Parks_pt_public", kind: "parks" },
  { service: "ABI_Art_Collections_public", kind: "art" },
  { service: "ABI_Trails_Access_pt_public", kind: "trail-access" },
];

const q = (s) =>
  `${BASE}/${s}/FeatureServer/0/query?where=1%3D1&outFields=*&outSR=4326&f=geojson`;

const clean = (v) => (typeof v === "string" ? v.trim() : v) || undefined;
const slug = (s, i) =>
  (s || `place-${i}`).toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "").slice(0, 48);

const out = [];
for (const { service, kind } of LAYERS) {
  const res = await fetch(q(service));
  const { features = [] } = await res.json();
  let kept = 0;

  for (const f of features) {
    const p = f.properties ?? {};
    const c = f.geometry?.coordinates;
    if (!c || !Number.isFinite(c[0]) || !Number.isFinite(c[1])) continue;

    let name, detail, url, img;
    if (kind === "parks") {
      name = clean(p.abi_name) ?? clean(p.coa_name);
      detail = clean(p.hours);
      url = clean(p.beltline_url);
    } else if (kind === "art") {
      name = clean(p.artwork);
      const artist = [clean(p.artist_first), clean(p.artist_last)].filter(Boolean).join(" ");
      detail = [artist, clean(p.year)].filter(Boolean).join(" · ") || clean(p.artwork_type_1);
      url = clean(p.url);
      img = clean(p.websiteimage);
      if (clean(p.activeinactive) === "Inactive") continue;
    } else {
      name = clean(p.name);
      detail = [clean(p.trail), clean(p.ada) === "Y" ? "ADA" : null].filter(Boolean).join(" · ");
      if (clean(p.public_) === "N" || clean(p.status) === "Closed") continue;
    }

    if (!name) continue; // unnamed features aren't useful to show
    out.push({ id: `${kind}-${slug(name, out.length)}`, name, kind, lng: +c[0].toFixed(6), lat: +c[1].toFixed(6), detail, url, img });
    kept++;
  }
  console.log(`${service}: ${features.length} fetched, ${kept} kept`);
}

// de-dupe ids (several artworks share a title across locations)
const seen = new Map();
for (const p of out) {
  const n = (seen.get(p.id) ?? 0) + 1;
  seen.set(p.id, n);
  if (n > 1) p.id = `${p.id}-${n}`;
}

const body = `// GENERATED by scripts/fetch-places.mjs -- do not edit by hand.
// Source: Atlanta BeltLine Inc public ArcGIS (gis.beltline.org). Location data
// only; no branding. Re-run the script to refresh.

export type PlaceKind = "parks" | "art" | "trail-access";

export interface Place {
  id: string;
  name: string;
  kind: PlaceKind;
  lng: number;
  lat: number;
  /** Park hours, "artist · year" for art, or "trail · ADA" for access points. */
  detail?: string;
  url?: string;
  img?: string;
}

export const places: Place[] = ${JSON.stringify(out, null, 2)};
`;
writeFileSync("src/lib/places.ts", body);
console.log(`\nwrote src/lib/places.ts — ${out.length} places`);
